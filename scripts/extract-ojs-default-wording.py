#!/usr/bin/env python3
"""Build scripts/ojs-default-wording.txt from the shipped OJS default texts.

OJS fills a new journal's settings (open access policy, privacy statement,
author guidelines, reader and librarian information, submission checklist,
LOCKSS and CLOCKSS texts) from `default.contextSettings.*` in
ojs-core/locale/en/default.po. If a journal keeps that text, it goes live as the
journal's own policy. `check-placeholders.sh --url` flags these fragments on the
rendered site.

  python3 -I scripts/extract-ojs-default-wording.py           write the list
  python3 -I scripts/extract-ojs-default-wording.py --check   fail if the list is out of date
                                                              (skips with a message if ojs-core/ is absent)

Re-run after every OJS pin change. Fragments are the first 70 characters of each
sentence of 40+ characters, lower-cased, tags and {$variables} removed. Matching is
a normalised substring match on the page's visible text: reliable for text that was
left as shipped, and it cannot see text a person has reworded (that is the intent).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "ojs-core/locale/en/default.po"
OUT = ROOT / "scripts/ojs-default-wording.txt"
KEY = "default.contextSettings."


def entries(po):
    key, val, cur = None, [], None
    for line in po.splitlines():
        if line.startswith("msgid "):
            if key is not None and cur == "str":
                yield key, "".join(val)
            key, val, cur = line[6:].strip().strip('"'), [], "id"
        elif line.startswith("msgstr "):
            cur, val = "str", [line[7:].strip().strip('"')]
        elif line.startswith('"') and cur == "str":
            val.append(line.strip().strip('"'))
    if key is not None and cur == "str":
        yield key, "".join(val)


def fragments(text):
    text = text.encode().decode("unicode_escape") if "\\" in text else text
    text = re.sub(r"\{\$[^}]*\}", ". ", text)
    text = re.sub(r"<[^>]+>", ". ", text)
    text = re.sub(r"\s+", " ", text)
    for sentence in re.split(r"(?<=[.!?])\s+|\.\s+", text):
        s = sentence.strip(" .,;:").lower()
        if len(s) >= 40:
            yield s[:70].rstrip()


def build():
    if not SRC.exists():
        return None
    out = set()
    for key, val in entries(SRC.read_text()):
        if key.startswith(KEY):
            out.update(fragments(val))
    header = ("# OJS 3.5.0-6 default wording (generated by scripts/extract-ojs-default-wording.py from\n"
              "# ojs-core/locale/en/default.po). One lower-case fragment per line. Do not edit by hand.\n")
    return header + "\n".join(sorted(out)) + "\n"


def main():
    new = build()
    if new is None:
        print("ojs-core/ not present: default-wording list not checked (run `make setup`)")
        return 0
    if "--check" in sys.argv[1:]:
        if OUT.exists() and OUT.read_text() == new:
            print(f"default-wording list is current ({new.count(chr(10)) - 2} fragments)")
            return 0
        print("scripts/ojs-default-wording.txt is out of date: run python3 -I scripts/extract-ojs-default-wording.py")
        return 1
    OUT.write_text(new)
    print(f"wrote {OUT.relative_to(ROOT)}: {new.count(chr(10)) - 2} fragments")
    return 0


if __name__ == "__main__":
    sys.exit(main())
