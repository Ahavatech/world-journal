#!/usr/bin/env bash
# Fetch Cloudflare's published IP ranges and write the Nginx real-IP include. Run at provision time and weekly.
#
#   scripts/update-cloudflare-ips.sh --out /etc/nginx/worj-cloudflare-realip.conf [options]
#
#   --out FILE          the include file to write (required)
#   --source BASE       where to fetch BASE/ips-v4 and BASE/ips-v6 (default https://www.cloudflare.com).
#                       Only https is accepted, plus file:// and http://127.0.0.1 / localhost for tests.
#   --test-cmd CMD      run after the new file is in place; non-zero restores the old file (default: nginx -t)
#   --reload-cmd CMD    run after a changed, tested file (default: systemctl reload nginx)
#   --no-reload         do not reload
#   --check             fetch and validate, print what would happen, write nothing
#
# Behaviour (so every visitor never looks like a Cloudflare address):
#   - the ranges are never hard-coded here; every line must be a valid CIDR, at least 10 IPv4 and 5 IPv6 lines,
#     no /0 and no range wider than /8 (IPv4) or /16 (IPv6), or the whole fetch is rejected
#   - on ANY failure the previous file is kept untouched and the exit code is non-zero (1)
#   - on the FIRST run, if no ranges exist yet and the fetch fails, exit 3 with a clear message: provisioning must
#     stop there rather than continue with real-IP handling unset
#   - prints `changed` or `unchanged`; the reload only happens after a changed file passed the test command
set -euo pipefail

out="" source_base="https://www.cloudflare.com" test_cmd="nginx -t" reload_cmd="systemctl reload nginx" reload=1 check=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --out) out="${2:?}"; shift 2 ;;
    --source) source_base="${2:?}"; shift 2 ;;
    --test-cmd) test_cmd="${2:?}"; shift 2 ;;
    --reload-cmd) reload_cmd="${2:?}"; shift 2 ;;
    --no-reload) reload=0; shift ;;
    --check) check=1; shift ;;
    -h | --help) sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d;s/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -n "$out" ] || { echo "ERROR: --out FILE is required" >&2; exit 2; }
case "$source_base" in
  https://* | file://* | http://127.0.0.1* | http://localhost*) ;;
  *) echo "REFUSED: --source must be https (or file:// or localhost for tests), got a different scheme" >&2; exit 2 ;;
esac

had_file=0; [ -s "$out" ] && had_file=1
tmp="$(mktemp -d)"
trap 'rm -rf -- "${tmp:?}"' EXIT

fail() { # message
  echo "ERROR: $1" >&2
  if [ "$had_file" = 1 ]; then echo "the previous ranges file is kept: $out" >&2; exit 1; fi
  echo "ERROR: no Cloudflare ranges exist yet ($out): without them Nginx would log every visitor as a Cloudflare address. Fix the fetch and run this script again before continuing." >&2
  exit 3
}

for v in v4 v6; do
  if ! curl --silent --show-error --fail --location --proto '=https,file,http' --max-time 30 --retry 2 --retry-delay 2 \
      -o "$tmp/ips-$v" "$source_base/ips-$v" 2>"$tmp/curl-$v.err"; then
    fail "could not fetch $source_base/ips-$v ($(tr '\n' ' ' <"$tmp/curl-$v.err" | cut -c1-120))"
  fi
done

if ! python3 -I - "$tmp/ips-v4" "$tmp/ips-v6" "$tmp/realip.conf" >"$tmp/validate.txt" 2>&1 <<'PY'
import ipaddress, sys
v4, v6, out = sys.argv[1:4]
def load(path, version, minimum, widest):
    nets = []
    for n, raw in enumerate(open(path, encoding="utf-8", errors="strict").read().splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        try:
            net = ipaddress.ip_network(line, strict=True)
        except ValueError:
            raise SystemExit(f"{path.rsplit('/', 1)[-1]} line {n} is not a CIDR range")
        if net.version != version:
            raise SystemExit(f"{path.rsplit('/', 1)[-1]} line {n} is the wrong address family")
        if net.prefixlen < widest:
            raise SystemExit(f"{path.rsplit('/', 1)[-1]} line {n} is too wide a range (/{net.prefixlen}): it would trust the whole internet")
        nets.append(net)
    if len(nets) < minimum:
        raise SystemExit(f"{path.rsplit('/', 1)[-1]} has {len(nets)} range(s), expected at least {minimum}")
    return nets
a = load(v4, 4, 10, 8)
b = load(v6, 6, 5, 16)
lines = ["# Cloudflare IP ranges for real client addresses. GENERATED by scripts/update-cloudflare-ips.sh; do not edit.",
         "# Source: Cloudflare's published lists, fetched at provision time and refreshed weekly (never hard-coded in the repo)."]
lines += [f"set_real_ip_from {n};" for n in a + b]
lines += ["real_ip_header CF-Connecting-IP;", "real_ip_recursive on;"]
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(a)} IPv4 and {len(b)} IPv6 ranges")
PY
then
  fail "the fetched lists were rejected: $(tr '\n' ' ' <"$tmp/validate.txt" | cut -c1-160)"
fi
summary="$(cat "$tmp/validate.txt")"

if [ "$had_file" = 1 ] && cmp -s "$tmp/realip.conf" "$out"; then echo "unchanged ($summary)"; exit 0; fi
if [ "$check" = 1 ]; then echo "would write $out ($summary); nothing written (--check)"; exit 0; fi

mkdir -p "$(dirname "$out")"
[ "$had_file" = 0 ] || cp -p "$out" "$tmp/previous"
install -m 644 "$tmp/realip.conf" "$out.new"
mv -f "$out.new" "$out"
# shellcheck disable=SC2086  # the test command is a command line given by the caller
if ! $test_cmd >"$tmp/test.txt" 2>&1; then
  if [ "$had_file" = 1 ]; then mv -f "$tmp/previous" "$out"; else rm -f "$out"; fi
  echo "ERROR: the web server configuration test failed with the new ranges; the previous state was restored" >&2
  [ "$had_file" = 1 ] && exit 1
  echo "ERROR: no Cloudflare ranges exist yet" >&2
  exit 3
fi
if [ "$reload" = 1 ]; then
  # shellcheck disable=SC2086
  $reload_cmd
fi
echo "changed ($summary)"
